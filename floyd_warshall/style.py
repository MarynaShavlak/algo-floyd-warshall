"""Єдина візуальна тема для всіх візуалізацій: палітра кольорів і параметри matplotlib.

Раніше кольори були частково іменованими константами, а частково «зашитими»
шестнадцятковими літералами просто в коді малювання. Тут усе зведено в одне
місце, щоб змінити вигляд можна було з однієї точки.
"""

from __future__ import annotations

import matplotlib.pyplot as plt

# ---------------------------------------------------------------------------
# Параметри фігур
# ---------------------------------------------------------------------------
#: DPI для всіх збережених/показаних фігур.
FIGURE_DPI: int = 110
#: DPI для GIF-анімацій (нижчий за статичні рисунки — менший розмір файлу).
GIF_DPI: int = 90
#: Базовий розмір шрифту matplotlib.
BASE_FONT_SIZE: int = 11
#: Сімейство шрифтів (містить кирилицю та символ ∞).
FONT_FAMILY: str = "DejaVu Sans"

# ---------------------------------------------------------------------------
# Палітра: заливки та обведення
# ---------------------------------------------------------------------------
#: 🟦 поточна проміжна вершина ``k`` — заливка / обведення рядка-стовпця.
BLUE_FILL, BLUE_EDGE = "#E3F2FD", "#1976D2"
#: 🟩 клітинка, що покращилася на кроці — заливка / текст.
GREEN_FILL, GREEN_TXT = "#C8E6C9", "#2E7D32"
#: Колір сітки матриці.
GRID_EDGE = "#CFCFCF"
#: Обведення опорного рядка/стовпця ``k``.
PIVOT_EDGE = "#1565C0"
#: 🟧 поточна клітинка ``(i, j)`` під час покрокового скану двох внутрішніх циклів.
SCAN_EDGE = "#F57C00"
#: 🔴 підсвічений найкоротший шлях (ребра/вершини графа, акценти на графіках).
PATH_COLOR = "#D32F2F"
#: Звичайна вершина графа.
NODE_COLOR = "#1f77b4"
#: Звичайні (непідсвічені) ребра графа та допоміжний сірий текст.
NEUTRAL_GRAY = "#9E9E9E"
#: Заливка клітинок діагоналі матриці.
DIAG_FILL = "#FAFAFA"

# ---------------------------------------------------------------------------
# Палітра: текстові відтінки
# ---------------------------------------------------------------------------
#: Підписи рядків/стовпців (заголовки матриці).
HEADER_TXT = "#555"
#: Другорядні підписи у формулі (``D[i][j]`` тощо).
SUBLABEL_TXT = "#777"
#: Приглушений сірий (заголовок ``i→j``, ∞ у великих матрицях, підписи).
MUTED_TXT = "#9aa0a6"
#: ∞ у компактній матриці (:func:`visualization.draw_matrix`).
INF_TXT_COMPACT = "#CFCFCF"
#: Звичайне (темне) значення клітинки в компактній матриці.
TEXT_DARK = "#222"
#: Числа у розгорнутій формулі кроку.
TEXT_FORMULA = "#3c4043"
#: Результат формули, що НЕ покращився (без зеленого).
TEXT_RESULT = "#1a1a1a"
#: Нульова вісь на графіку розбіжності ваги.
AXIS_LINE = "#999"


def configure_style() -> None:
    """Налаштовує глобальні параметри matplotlib (DPI, шрифт із кирилицею та ∞)."""
    plt.rcParams["figure.dpi"] = FIGURE_DPI
    plt.rcParams["font.size"] = BASE_FONT_SIZE
    plt.rcParams["font.family"] = FONT_FAMILY
    # анімації тримають десятки кадрів-фігур водночас до зшивання у GIF —
    # вимикаємо попередження «надто багато відкритих фігур» (їх закриває save_gif)
    plt.rcParams["figure.max_open_warning"] = 0
