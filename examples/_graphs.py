"""Дані прикладів — єдине джерело правди для трьох навчальних графів.

Раніше ті самі матриці суміжності й координати дублювалися між скриптами
``examples/`` (граф ``A–F`` описували і ``00``, і ``01``, і ``04``; ``P–Q–R–S`` —
``03`` і ``04``; цикл ``X–Y–Z`` — ``02`` і ``04``). Тут вони зведені в одне
місце; кожен приклад лише імпортує потрібний граф.

Кожен граф — :class:`_common.GraphExample`: мітки вершин + матриця суміжності в
угоді ``0 == немає ребра`` + координати ``{індекс: (x, y)}`` для малювання.
"""

from __future__ import annotations

from _common import GraphExample

#: Основний приклад: орієнтований граф ``A–F``, лише додатні ваги (приклади 00, 01, 04).
ABCDEF = GraphExample(
    labels=["A", "B", "C", "D", "E", "F"],
    adjacency=[
        [0, 3, 0, 0, 0, 0],   # A → B (3)
        [0, 0, 1, 0, 0, 0],   # B → C (1)
        [0, 0, 0, 7, 0, 2],   # C → D (7), C → F (2)
        [0, 0, 0, 0, 0, 0],   # D — стік
        [0, 0, 0, 2, 0, 3],   # E → D (2), E → F (3)
        [0, 0, 0, 0, 0, 0],   # F — стік
    ],
    positions={0: (3.4, 2.6), 1: (3.0, 1.7), 2: (2.0, 1.7),
               3: (2.1, 0.0), 4: (0.9, 1.7), 5: (0.4, 2.7)},
)

#: Від'ємне ребро ``Q → R = −2`` (приклади 03, 04): пряме ``P → S = 10`` програє
#: шляху ``P → Q → R → S = 5``.
PQRS = GraphExample(
    labels=["P", "Q", "R", "S"],
    adjacency=[
        [0, 4, 0, 10],   # P → Q (4),  P → S (10)
        [0, 0, -2, 0],   # Q → R (-2)   ← від'ємне ребро
        [0, 0, 0, 3],    # R → S (3)
        [0, 0, 0, 0],    # S — без вихідних ребер
    ],
    positions={0: (0.3, 1.0), 1: (1.5, 1.9), 2: (2.9, 1.9), 3: (4.1, 1.0)},
)

#: Повністю від'ємний цикл ``X → Y → Z → X``, кожне ребро ``−1`` (приклади 02, 04).
XYZ = GraphExample(
    labels=["X", "Y", "Z"],
    adjacency=[
        [0, -1, 0],   # X → Y (-1)
        [0, 0, -1],   # Y → Z (-1)
        [-1, 0, 0],   # Z → X (-1)
    ],
    positions={0: (1.5, 2.2), 1: (2.7, 0.4), 2: (0.3, 0.4)},  # X угорі, Y і Z знизу
)
